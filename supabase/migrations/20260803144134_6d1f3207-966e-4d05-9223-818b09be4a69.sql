-- ============ 2. LEGAL DOCUMENTS ============
CREATE TABLE IF NOT EXISTS public.legal_documents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE,
  page_label text NOT NULL DEFAULT '',
  title text NOT NULL DEFAULT '',
  eyebrow text NOT NULL DEFAULT '',
  intro text NOT NULL DEFAULT '',
  published_content text NOT NULL DEFAULT '',
  draft_content text NOT NULL DEFAULT '',
  published_at timestamptz,
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by_email text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.legal_document_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  document_id uuid NOT NULL REFERENCES public.legal_documents(id) ON DELETE CASCADE,
  title text NOT NULL DEFAULT '',
  intro text NOT NULL DEFAULT '',
  content text NOT NULL DEFAULT '',
  published_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  published_by_email text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS legal_document_versions_doc_idx
  ON public.legal_document_versions (document_id, created_at DESC);

-- Grants: public may read ONLY published columns; admins get full access.
GRANT SELECT (id, slug, page_label, title, eyebrow, intro, published_content, published_at, updated_at)
  ON public.legal_documents TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.legal_documents TO authenticated;
GRANT ALL ON public.legal_documents TO service_role;

GRANT SELECT, INSERT, DELETE ON public.legal_document_versions TO authenticated;
GRANT ALL ON public.legal_document_versions TO service_role;

ALTER TABLE public.legal_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.legal_document_versions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "legal docs public read" ON public.legal_documents;
CREATE POLICY "legal docs public read" ON public.legal_documents
  FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "legal docs admin write" ON public.legal_documents;
CREATE POLICY "legal docs admin write" ON public.legal_documents
  FOR ALL TO authenticated
  USING (app_private.has_role(auth.uid(), 'admin'))
  WITH CHECK (app_private.has_role(auth.uid(), 'admin'));

DROP POLICY IF EXISTS "legal versions admin" ON public.legal_document_versions;
CREATE POLICY "legal versions admin" ON public.legal_document_versions
  FOR ALL TO authenticated
  USING (app_private.has_role(auth.uid(), 'admin'))
  WITH CHECK (app_private.has_role(auth.uid(), 'admin'));

DROP TRIGGER IF EXISTS update_legal_documents_updated_at ON public.legal_documents;
CREATE TRIGGER update_legal_documents_updated_at
  BEFORE UPDATE ON public.legal_documents
  FOR EACH ROW EXECUTE FUNCTION app_private.touch_updated_at();

